  function toImageData(key, rows) {
    if (!Array.isArray(rows) || rows.length === 0) throw new Error('PixelArt: sprite "' + key + '" has no rows');
    const w = rows[0].length;
    rows.forEach((r, y) => {
      if (r.length !== w) {
        throw new Error('PixelArt: sprite "' + key + '" row ' + y + ' is ' + r.length + ' px wide, expected ' + w);
      }
    });
    const c = document.createElement('canvas');
    c.width = w; c.height = rows.length;
    const g = c.getContext('2d');
    rows.forEach((r, y) => [...r].forEach((ch, x) => {
      if (ch === '.') return;
      const col = PALETTE[ch];
      if (!col) throw new Error('PixelArt: sprite "' + key + '" uses unknown colour "' + ch + '" at ' + x + ',' + y);
      g.fillStyle = col; g.fillRect(x, y, 1, 1);
    }));
    return g.getImageData(0, 0, c.width, c.height);
  }

